-- ------------------------------------------------------------------------------
-- 16. LADDER ROSTERS
-- ------------------------------------------------------------------------------
CREATE TABLE public.ladder_rosters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT REFERENCES public.ladder_teams(id) ON DELETE CASCADE,
    gamertag TEXT NOT NULL,
    discord_username TEXT,
    role TEXT DEFAULT 'member',
    joined_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 17. LADDER MATCHES
-- ------------------------------------------------------------------------------
CREATE TABLE public.ladder_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ladder_type TEXT NOT NULL DEFAULT '4v4_variant',
    team_a_id BIGINT REFERENCES public.ladder_teams(id) ON DELETE CASCADE,
    team_b_id BIGINT REFERENCES public.ladder_teams(id) ON DELETE SET NULL,
    team_a_score INT DEFAULT 0,
    team_b_score INT DEFAULT 0,
    best_of INT DEFAULT 5,
    status TEXT DEFAULT 'open',
    scheduled_time TIMESTAMPTZ DEFAULT NOW(),
    winner_id BIGINT REFERENCES public.ladder_teams(id) ON DELETE SET NULL,
    reported_by TEXT,
    proof_url TEXT,
    notes TEXT,
    maps_played JSONB,
    elo_change INT DEFAULT 25,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    completed_at TIMESTAMPTZ
);

-- ------------------------------------------------------------------------------
-- 18. LADDER DISPUTES
-- ------------------------------------------------------------------------------
CREATE TABLE public.ladder_disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT REFERENCES public.ladder_matches(id) ON DELETE CASCADE,
    disputing_team_id BIGINT REFERENCES public.ladder_teams(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    proof_url TEXT,
    status TEXT DEFAULT 'pending',
    resolved_by TEXT,
    resolution_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    resolved_at TIMESTAMPTZ
);

-- ------------------------------------------------------------------------------
-- 19. STAFF ROLES (RBAC FOR ADMIN PORTAL)
-- ------------------------------------------------------------------------------
CREATE TABLE public.staff_roles (
