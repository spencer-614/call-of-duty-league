    start_date TEXT,
    start_time TEXT,
    status TEXT DEFAULT 'Registration Open',
    image_url TEXT,
    registration_url TEXT,
    bracket_url TEXT,
    description TEXT,
    rules_notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 13c. TOURNAMENT REGISTRATIONS (LOGGED SQUAD ENTRIES & ROSTERS)
