-- ------------------------------------------------------------------------------
-- 1. AUTH COMPATIBILITY & PRIVATE SCHEMAS
-- ------------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS auth;

CREATE TABLE IF NOT EXISTS auth.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT UNIQUE,
    raw_user_meta_data JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE SCHEMA IF NOT EXISTS fcl_private;

-- ------------------------------------------------------------------------------
-- 2. LEAGUE TEAMS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    tag TEXT NOT NULL,
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    points INT DEFAULT 0,
    logo_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 3. LEAGUE PLAYERS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    gamertag TEXT NOT NULL UNIQUE,
    real_name TEXT,
    role TEXT DEFAULT 'Flex',
    kdr NUMERIC(4, 2) DEFAULT 1.00,
    total_kills INT DEFAULT 0,
    total_deaths INT DEFAULT 0,
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    activision_id TEXT,
    discord_name TEXT,
    region TEXT DEFAULT 'NA East',
    platform TEXT DEFAULT 'PC',
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_players_user_id ON public.players(user_id);
CREATE INDEX idx_players_gamertag_lower ON public.players(LOWER(gamertag));
CREATE INDEX idx_players_team_id ON public.players(team_id);

-- ------------------------------------------------------------------------------
-- 4. VODS & LIVESTREAMS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.vods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    stage TEXT DEFAULT 'Regular Season',
    match_date DATE DEFAULT CURRENT_DATE,
    team1_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    team2_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    team1_score INT DEFAULT 0,
    team2_score INT DEFAULT 0,
    vod_url TEXT NOT NULL,
    is_live BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 5. INDIVIDUAL PLAYER MAP STATS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.player_map_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT REFERENCES public.players(id) ON DELETE CASCADE,
    map_name TEXT NOT NULL,
    game_mode TEXT NOT NULL,
    opponent_team TEXT,
    kills INT DEFAULT 0,
    deaths INT DEFAULT 0,
    damage INT DEFAULT 0,
    kdr NUMERIC(4, 2) DEFAULT 1.00,
    result TEXT DEFAULT 'W',
    score TEXT,
    match_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_player_map_stats_player ON public.player_map_stats(player_id);

-- ------------------------------------------------------------------------------
-- 6. TEAM MAP RECORDS TABLE
-- ------------------------------------------------------------------------------
CREATE TABLE public.team_map_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT REFERENCES public.teams(id) ON DELETE CASCADE,
    map_name TEXT NOT NULL,
    game_mode TEXT NOT NULL,
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    win_rate INT DEFAULT 0,
    streak TEXT DEFAULT '1W',
    recent_score TEXT,
    recent_result TEXT DEFAULT 'W',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_team_map_records_team ON public.team_map_records(team_id);

-- ------------------------------------------------------------------------------
-- 7. LEAGUE SIGNUPS / FREE AGENT QUEUE
-- ------------------------------------------------------------------------------
CREATE TABLE public.league_signups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    gamertag TEXT NOT NULL,
    activision_id TEXT,
    discord_username TEXT NOT NULL,
    discord_user_id TEXT,
    role TEXT DEFAULT 'Flex',
    platform TEXT DEFAULT 'PC',
    region TEXT DEFAULT 'NA East',
    registration_type TEXT DEFAULT 'Free Agent',
    team_name TEXT,
    notes TEXT,
    status TEXT DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_league_signups_user_id ON public.league_signups(user_id);
CREATE INDEX idx_league_signups_gamertag ON public.league_signups(gamertag);
CREATE INDEX idx_league_signups_discord_id ON public.league_signups(discord_user_id);

