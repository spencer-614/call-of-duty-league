-- ------------------------------------------------------------------------------
-- 13. TOURNAMENT MATCHES & BRACKETS
-- ------------------------------------------------------------------------------
CREATE TABLE public.tournament_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id TEXT REFERENCES public.tournament_divisions(id) ON DELETE CASCADE,
    match_code TEXT NOT NULL,
    round_name TEXT NOT NULL,
    stage TEXT NOT NULL,
    round_order INT DEFAULT 1,
    match_order INT DEFAULT 1,
    team1_name TEXT NOT NULL,
    team1_tag TEXT NOT NULL,
    team1_seed INT,
    team1_score INT DEFAULT 0,
    team2_name TEXT NOT NULL,
    team2_tag TEXT NOT NULL,
    team2_seed INT,
    team2_score INT DEFAULT 0,
    winner_name TEXT,
    status TEXT DEFAULT 'Scheduled',
    scheduled_time TEXT,
    best_of INT DEFAULT 5,
    mvp_gamertag TEXT,
    mvp_stats TEXT,
    vod_url TEXT,
    maps_data JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_tournament_matches_division ON public.tournament_matches(division_id);

-- ------------------------------------------------------------------------------
