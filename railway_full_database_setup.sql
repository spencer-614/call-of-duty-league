-- ------------------------------------------------------------------------------
-- 10. LEAGUE SEASON SETTINGS
-- ------------------------------------------------------------------------------
CREATE TABLE public.league_settings (
    id TEXT PRIMARY KEY,
    season_number INT DEFAULT 1,
    status_state TEXT DEFAULT 'active',
    status_text TEXT DEFAULT 'SEASON 1 ACTIVE',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- 11. SCHEDULED MATCHES (8-WEEK MATCH SCHEDULE)
-- ------------------------------------------------------------------------------
CREATE TABLE public.scheduled_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    week_number INT NOT NULL,
    season_type TEXT NOT NULL DEFAULT 'regular',
    week_label TEXT NOT NULL,
    match_number INT DEFAULT 1,
    team1_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    team1_name TEXT NOT NULL,
    team1_tag TEXT NOT NULL,
    team1_score INT DEFAULT 0,
    team2_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    team2_name TEXT NOT NULL,
    team2_tag TEXT NOT NULL,
    team2_score INT DEFAULT 0,
    winner_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    winner_name TEXT,
    status TEXT DEFAULT 'Scheduled',
    scheduled_date DATE DEFAULT CURRENT_DATE,
    scheduled_time TEXT DEFAULT '7:00 PM EST',
    best_of INT DEFAULT 5,
    stream_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_scheduled_matches_week ON public.scheduled_matches(week_number);
CREATE INDEX idx_scheduled_matches_season ON public.scheduled_matches(season_type);

-- ------------------------------------------------------------------------------
-- 12. TOURNAMENT DIVISIONS
-- ------------------------------------------------------------------------------
CREATE TABLE public.tournament_divisions (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    tier TEXT DEFAULT 'Division 1',
