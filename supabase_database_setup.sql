-- ------------------------------------------------------------------------------
-- TEAMS
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    tag TEXT NOT NULL,
    division TEXT DEFAULT 'div-1',
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    points INT DEFAULT 0,
    logo_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ------------------------------------------------------------------------------
-- PLAYERS
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT REFERENCES public.teams(id) ON DELETE SET NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    email TEXT,
    gamertag TEXT NOT NULL UNIQUE,
    real_name TEXT,
    role TEXT DEFAULT 'Flex',
    kdr NUMERIC(4, 2) DEFAULT 1.00,
    total_kills INT DEFAULT 0,
    total_deaths INT DEFAULT 0,
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    activision_id TEXT,
    discord_name TEXT,
    region TEXT DEFAULT 'NA East',
    platform TEXT DEFAULT 'PC',
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.players ADD COLUMN IF NOT EXISTS email TEXT;
CREATE INDEX IF NOT EXISTS idx_players_email ON public.players(LOWER(email));
CREATE INDEX IF NOT EXISTS idx_players_user_id ON public.players(user_id);
