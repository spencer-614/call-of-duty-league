-- ==============================================================================
-- FRONTLINE ARENA - ROW LEVEL SECURITY (RLS) POLICIES & MISSING TABLES MIGRATION
-- ==============================================================================
-- Ensures public access (select, insert, update, delete) for all Arena Ladder
-- and Free Agent tables, allowing users authenticated via Discord or website
-- to be properly listed and visible across all clients.
-- ==============================================================================

-- 1. ARENA FREE AGENTS TABLE & POLICIES
CREATE TABLE IF NOT EXISTS public.arena_free_agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    gamertag TEXT NOT NULL UNIQUE,
    clan_tag VARCHAR(6) DEFAULT 'LFT',
    avatar_url TEXT DEFAULT 'https://images.unsplash.com/photo-1542751371-adc38448a05e?w=150&auto=format&fit=crop&q=80',
    ladder_pref TEXT NOT NULL DEFAULT '4v4_variant',
    primary_role TEXT DEFAULT 'Flex',
    secondary_role TEXT DEFAULT 'Main AR',
    elo INT DEFAULT 1200,
    kdr NUMERIC(4,2) DEFAULT 1.00,
    platform TEXT DEFAULT 'PC',
    region TEXT DEFAULT 'NA East',
    discord TEXT,
    activision_id TEXT,
    availability TEXT DEFAULT 'Active / Daily',
    bio TEXT DEFAULT 'Competitive operator looking for team.',
    mic BOOLEAN DEFAULT TRUE,
    is_active BOOLEAN DEFAULT TRUE,
    is_new_user BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_arena_fa_gamertag ON public.arena_free_agents (LOWER(gamertag));
CREATE INDEX IF NOT EXISTS idx_arena_fa_user_id ON public.arena_free_agents (user_id);
CREATE INDEX IF NOT EXISTS idx_arena_fa_ladder_pref ON public.arena_free_agents (ladder_pref);

ALTER TABLE public.arena_free_agents ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public all arena_free_agents" ON public.arena_free_agents;
DROP POLICY IF EXISTS "Allow public read arena_free_agents" ON public.arena_free_agents;
DROP POLICY IF EXISTS "Allow public insert arena_free_agents" ON public.arena_free_agents;
DROP POLICY IF EXISTS "Allow public update arena_free_agents" ON public.arena_free_agents;
DROP POLICY IF EXISTS "Allow public delete arena_free_agents" ON public.arena_free_agents;

CREATE POLICY "Allow public all arena_free_agents" 
ON public.arena_free_agents 
FOR ALL 
USING (true) 
WITH CHECK (true);

