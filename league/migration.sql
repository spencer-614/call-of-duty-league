LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE zone text;
BEGIN
 IF NEW.fcl_season_id IS NOT NULL AND NEW.scheduled_time IS NOT NULL AND upper(NEW.scheduled_time)<>'TBD' THEN
  IF TG_OP='INSERT' OR (NEW.fcl_scheduled_at IS NOT DISTINCT FROM OLD.fcl_scheduled_at AND (NEW.scheduled_date IS DISTINCT FROM OLD.scheduled_date OR NEW.scheduled_time IS DISTINCT FROM OLD.scheduled_time)) THEN
   SELECT timezone INTO zone FROM fcl_seasons WHERE id=NEW.fcl_season_id;
   NEW.fcl_scheduled_at := (NEW.scheduled_date + regexp_replace(NEW.scheduled_time,'\s+(EST|EDT|ET|UTC|GMT)$','','i')::time) AT TIME ZONE zone;
  END IF;
 END IF;
 RETURN NEW;
END $$;
