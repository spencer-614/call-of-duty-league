CREATE OR REPLACE FUNCTION public.fcl_check_signup() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 -- The database owner's maintenance path and trusted staff may manage approvals.
 IF auth.uid() IS NOT NULL AND NOT public.fcl_is_staff() THEN
  IF NEW.user_id IS DISTINCT FROM auth.uid() THEN RAISE EXCEPTION 'Registration must belong to signed-in account'; END IF;
  IF lower(COALESCE(NEW.status,'pending'))<>'pending' THEN RAISE EXCEPTION 'Only staff may approve registration'; END IF;
  SELECT COALESCE(i.provider_id,i.identity_data->>'sub',i.identity_data->>'id') INTO NEW.discord_user_id
   FROM auth.identities i WHERE i.user_id=auth.uid() AND i.provider='discord' LIMIT 1;
  IF NEW.discord_user_id IS NULL THEN RAISE EXCEPTION 'Sign in with Discord before registering'; END IF;
 END IF;
 RETURN NEW;
END $$;
