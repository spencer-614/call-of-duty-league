 SELECT t.team_id,t.season_id,t.name,t.tag,t.division,
 count(m.id) FILTER(WHERE m.winner_id=t.team_id)::int AS wins,
 count(m.id) FILTER(WHERE m.winner_id<>t.team_id)::int AS losses,
 COALESCE(sum(CASE WHEN m.team1_id=t.team_id THEN m.team1_score-m.team2_score ELSE m.team2_score-m.team1_score END),0)::int AS map_difference
 FROM public.fcl_season_teams t JOIN public.fcl_seasons s ON s.id=t.season_id AND s.status='active'
 LEFT JOIN public.scheduled_matches m ON m.fcl_season_id=t.season_id AND m.season_type='regular'
 AND (m.team1_id=t.team_id OR m.team2_id=t.team_id) AND m.winner_id IS NOT NULL
 AND lower(m.status) IN ('completed','complete','final','forfeit')
 GROUP BY t.team_id,t.season_id,t.name,t.tag,t.division;
