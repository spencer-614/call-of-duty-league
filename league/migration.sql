CREATE OR REPLACE FUNCTION public.fcl_advance_playoffs(sid bigint) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE r record;
BEGIN
 FOR r IN SELECT m.winner_id,m.winner_name,l.next_id,l.next_side,t.tag
  FROM scheduled_matches m JOIN fcl_playoff_links l ON l.match_id=m.id
  JOIN teams t ON t.id=m.winner_id
  WHERE m.fcl_season_id=sid AND lower(m.status) IN ('completed','complete','final','forfeit')
  AND m.winner_id IS NOT NULL ORDER BY m.fcl_round LOOP
  IF r.next_side=1 THEN
   UPDATE scheduled_matches SET team1_id=r.winner_id,team1_name=r.winner_name,team1_tag=r.tag WHERE id=r.next_id;
  ELSE
   UPDATE scheduled_matches SET team2_id=r.winner_id,team2_name=r.winner_name,team2_tag=r.tag WHERE id=r.next_id;
  END IF;
 END LOOP;
END $$;
