 available_at=now(),last_error=NULL WHERE fcl_jobs.status <> 'running';
$$;
CREATE OR REPLACE FUNCTION public.fcl_player_changed() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
DECLARE did text; old_did text; sid bigint;
BEGIN
 IF TG_OP='DELETE' THEN
   SELECT discord_id INTO did FROM fcl_identities WHERE player_id=OLD.id;
   IF did IS NOT NULL THEN PERFORM fcl_enqueue('member:'||did,'member',jsonb_build_object('discord_id',did)); END IF;
   RETURN OLD;
 END IF;
 SELECT discord_id INTO old_did FROM fcl_identities WHERE player_id=NEW.id;
 -- Identity comes from provider-owned OAuth records, NEVER a typed Discord name/ID.
 SELECT COALESCE(i.provider_id,i.identity_data->>'sub',i.identity_data->>'id') INTO did
 FROM auth.identities i WHERE i.user_id=NEW.user_id AND i.provider='discord' LIMIT 1;
 IF did ~ '^[0-9]{15,22}$' THEN
   INSERT INTO fcl_identities(player_id,discord_id) VALUES(NEW.id,did)
   ON CONFLICT(player_id) DO UPDATE SET discord_id=excluded.discord_id;
 END IF;
 SELECT discord_id INTO did FROM fcl_identities WHERE player_id=NEW.id;
 IF old_did IS NOT NULL AND old_did IS DISTINCT FROM did THEN PERFORM fcl_enqueue('member:'||old_did,'member',jsonb_build_object('discord_id',old_did)); END IF;
 IF did IS NOT NULL THEN PERFORM fcl_enqueue('member:'||did,'member',jsonb_build_object('discord_id',did)); END IF;
 SELECT id INTO sid FROM fcl_seasons WHERE status='active';
 IF sid IS NOT NULL THEN
   INSERT INTO fcl_roster_history(season_id,player_id,gamertag,team_id) VALUES(sid,NEW.id,NEW.gamertag,NEW.team_id);
 END IF;
 RETURN NEW;
END $$;
